const allCards=Array.from(projectTrack.querySelectorAll(".project"));
let pos=N;
const projectDots=document.getElementById("projectDots");
const projectCounter=document.getElementById("projectCounter");
let activeProject=0;
const reduceMotion=window.matchMedia("(prefers-reduced-motion: reduce)");
let carouselVisible=true;
function syncVideos(){
  allCards.forEach((card,index)=>{
    const v=card.querySelector("video");
    if(!v)return;
    if(index===pos&&carouselVisible&&!reduceMotion.matches){
      if(!v.getAttribute("src")&&v.dataset.src)v.src=v.dataset.src;
      v.muted=true;
      const p=v.play();
      if(p&&p.catch)p.catch(()=>{});
    }else v.pause();
  });
}
function renderProjectCarousel(){
  if(!projectCards.length)return;
  const total=N;
  activeProject=((pos%N)+N)%N;
  allCards.forEach((card,index)=>{
    card.classList.toggle("is-active",index===pos);
    card.classList.toggle("is-near",index===pos-1||index===pos+1);
    card.inert=index!==pos; /* liens non focusables et masqués aux lecteurs d'écran */
  });
  const card=allCards[pos];
  const frame=projectTrack.parentElement;
  const offset=card.offsetLeft-(frame.clientWidth-card.offsetWidth)/2;
  projectTrack.style.transform=`translateX(${-offset}px)`;
  projectCounter.textContent=`${String(activeProject+1).padStart(2,"0")} / ${String(total).padStart(2,"0")}`;
  Array.from(projectDots.children).forEach((dot,index)=>dot.setAttribute("aria-current",index===activeProject?"true":"false"));
  syncVideos();
}
let snapTimer=0;
function snapToMiddle(){
  clearTimeout(snapTimer);
  if(pos>=N&&pos<2*N)return;
  pos=((pos%N)+N)%N+N;
  projectTrack.classList.add("no-anim");
  renderProjectCarousel();
  void projectTrack.offsetWidth;
  projectTrack.classList.remove("no-anim");
}
function goTo(next){
  if(pos<0||pos>=3*N)snapToMiddle();
  pos=next;renderProjectCarousel();
  clearTimeout(snapTimer);snapTimer=setTimeout(snapToMiddle,620);
}
function moveProject(step){goTo(pos+step);}
projectCards.forEach((_,index)=>{
  const dot=document.createElement("button");
  dot.type="button";dot.className="carousel-dot";
  dot.addEventListener("click",()=>{if(pos<N||pos>=2*N)snapToMiddle();goTo(N+index);});
  projectDots.appendChild(dot);
});
