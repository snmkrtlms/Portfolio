const FORM_ENDPOINT="https://formspree.io/f/mrppgzbr";
(()=>{
  const form=document.getElementById("contactForm");if(!form)return;
  const status=document.getElementById("cf-status"),btn=document.getElementById("cf-send");
  const say=(k,c)=>{status.textContent=copy[lang][k];status.className="form-status "+(c||"");status.dataset.k=k};
  form.addEventListener("submit",async e=>{
    e.preventDefault();
    const f=new FormData(form);
    if(f.get("_gotcha"))return;
    const fields=[...form.querySelectorAll("input[required],textarea[required]")];
    let ok=true;fields.forEach(el=>{const v=el.checkValidity()&&el.value.trim()!=="";el.setAttribute("aria-invalid",v?"false":"true");if(!v)ok=false});
    if(!ok){say("fInvalid","err");return}
    btn.disabled=true;say("fSending");
    try{
      const r=await fetch(FORM_ENDPOINT,{method:"POST",body:f,headers:{Accept:"application/json"}});
      if(!r.ok)throw 0;
      form.reset();say("fOk","ok");
    }catch(_){say("fErr","err")}
    btn.disabled=false;
  });
  langBtn.addEventListener("click",()=>{if(status.dataset.k)status.textContent=copy[lang][status.dataset.k]});
})();
